CREATE TABLE IF NOT EXISTS motorista (
    id INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    cpf VARCHAR(11) NOT NULL UNIQUE,
    cnh VARCHAR(20) NOT NULL UNIQUE,
    telefone VARCHAR(20)
);

CREATE TABLE IF NOT EXISTS veiculo (
    id INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    placa VARCHAR(10) NOT NULL UNIQUE,
    modelo VARCHAR(100) NOT NULL,
    capacidade_kg NUMERIC(10,2) NOT NULL CHECK (capacidade_kg > 0),
    ano INTEGER NOT NULL CHECK (ano BETWEEN 1900 AND 2100)
);

CREATE TABLE IF NOT EXISTS entrega (
    id INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    descricao VARCHAR(255) NOT NULL,
    endereco_destino VARCHAR(255) NOT NULL,
    cep VARCHAR(8),
    data_entrega DATE,
    status VARCHAR(30) NOT NULL DEFAULT 'PENDENTE'
        CHECK (status IN ('PENDENTE', 'EM_TRANSITO', 'ENTREGUE', 'CANCELADA')),
    motorista_id INTEGER NOT NULL REFERENCES motorista(id) ON DELETE RESTRICT,
    veiculo_id INTEGER NOT NULL REFERENCES veiculo(id) ON DELETE RESTRICT
);